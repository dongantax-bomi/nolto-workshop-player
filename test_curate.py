import unittest
import json
import tempfile
from pathlib import Path
from unittest.mock import patch
from curate import is_art_track,art_matches,excluded,find_pair,apply_section_overrides,lyric_matches,recording_version_allowed,passage_from_lines

class CurationTests(unittest.TestCase):
    def test_display_lines_cannot_change_selected_words(self):
        lyric=dict(syncedLyrics='[00:10]first phrase (hey) second phrase\n[00:20]next section')
        spec=dict(first_line=0,stop_before_line=1,omit_parenthetical_adlibs=True,
                  answer_format='first phrase\nsecond phrase')
        self.assertEqual(passage_from_lines(lyric,spec)[2],'first phrase\nsecond phrase')
        with self.assertRaises(ValueError):
            passage_from_lines(lyric,dict(spec,answer_format='first changed phrase'))
        lyric=dict(syncedLyrics='[00:10]Hey, I just wanna be with you\n[00:20]next')
        spec=dict(first_line=0,stop_before_line=1,omit_leading_adlib='Hey, ')
        self.assertEqual(passage_from_lines(lyric,spec)[2],'I just wanna be with you')
        with self.assertRaises(ValueError):
            passage_from_lines(lyric,dict(spec,omit_leading_adlib='Wrong prefix'))

    def setUp(self):
        self.song={'id':60,'artist':'BTS','title':'Dynamite','section_hint':'1절 벌스 (영어)'}
        self.video={'title':'Dynamite','channel':'BTS','duration':200,'description':'Provided to YouTube by BigHit\n\nDynamite · BTS\n\nAlbum\n℗ BigHit\nAuto-generated by YouTube.','embed_verified':True,'playability':'OK'}
    def test_distribution_description_required(self):
        self.assertTrue(art_matches(self.video,self.song))
        self.assertFalse(is_art_track(dict(self.video,description='Official Audio')))
        self.assertFalse(art_matches(dict(self.video,title='Dynamite Official MV'),self.song))
    def test_album_title_cannot_impersonate_artist(self):
        cover=dict(self.video,description='Provided to YouTube by Label\nDynamite · Tribute Band\nTribute to BTS\n℗ Label\nAuto-generated by YouTube.')
        self.assertFalse(art_matches(cover,self.song))

    def test_actual_catalog_rejects_hidden_recording_versions(self):
        for description in [
            'Provided to YouTube by YGEX\n\nSong · Artist\n\nALIVE -MONSTER EDITION-\nAVEX MUSIC',
            'Provided to YouTube by Label\n\nA very long title (Inst.) · Artist\n\nOriginal Soundtrack',
            'Provided to YouTube by Label\n\nSong · Artist\n\nFamous Singers (From the "JTBC" TV SHOW)',
        ]:
            self.assertFalse(recording_version_allowed(dict(title='A very long title...',description=description)))
        spoof=dict(self.video,channel='surround. - Topic',description='Provided to YouTube by Label\nDynamite · surround. · BTS\nAuto-generated by YouTube.')
        self.assertFalse(art_matches(spoof,self.song))
    def test_lyrics_for_different_recording_length_rejected(self):
        lyrics='\n'.join(f'[00:{10+i*5:02d}.00]original test line number {i}' for i in range(10))
        with patch('curate.section_specs',return_value={}):
            self.assertIsNone(find_pair(self.video,[dict(duration=220,syncedLyrics=lyrics)],self.song))
            self.assertIsNotNone(find_pair(self.video,[dict(duration=200,syncedLyrics=lyrics)],self.song))
    def test_alternate_versions_rejected(self):
        for title in ['Song M/V','Song (Inst.)','Song Japanese Version','Song Live','Song Piano Cover','Whiplash (English Version)','Way Back Home (Sam Feldt Edit)']:
            self.assertTrue(excluded(title))

    def test_korean_song_rejects_romanized_and_japanese_lyric_sources(self):
        song=dict(id=2,artist='씨엔블루',title='외톨이야')
        item=dict(trackName='외톨이야',artistName='씨엔블루')
        self.assertFalse(lyric_matches(dict(item,syncedLyrics='[00:10]oetoriya oetoriya'),song))
        self.assertFalse(lyric_matches(dict(item,syncedLyrics='[00:10]日本語の歌です'),song))
        self.assertTrue(lyric_matches(dict(item,syncedLyrics='[00:10]상대의 눈빛과 달라진 태도를 보며 멀어진 관계를 알아차리는 이야기'),song))

    def test_reviewed_pair_uses_the_passage_even_when_longer_than_35_seconds(self):
        spec=dict(lyric_id=7,first_line=1,stop_before_line=4,youtube_id='AAAAAAAAAAA')
        lyric=dict(id=7,duration=100,syncedLyrics='[00:01]intro\n[00:10]first complete sentence\n[00:24]second complete sentence\n[00:38]third complete sentence\n[00:50]chorus')
        video=dict(self.video,id='AAAAAAAAAAA',duration=100)
        with patch('curate.section_specs',return_value={'60':spec}):
            pair=find_pair(video,[lyric],self.song)
            self.assertEqual(pair[3:5],(10,50))
            self.assertIsNone(find_pair(dict(video,id='BBBBBBBBBBB'),[lyric],self.song))

    def test_editorial_passage_keeps_all_lines_and_rejects_different_source(self):
        with tempfile.TemporaryDirectory(dir=Path(__file__).resolve().parent) as folder:
            root=Path(folder)
            (root/'section_overrides.json').write_text(json.dumps({'1':dict(lyric_id=7,first_line=1,stop_before_line=4,reason='Complete passage')}),encoding='utf-8')
            lyrics={7:dict(syncedLyrics='[00:01]intro\n[00:10]first\n[00:24]middle\n[00:38]last\n[00:50]chorus')}
            row=dict(id=1,youtube_id='abcdefghijk',lyric_id=7,video_duration=100)
            with patch('curate.ROOT',root):
                result=apply_section_overrides([row],lyrics)[0]
                self.assertEqual((result['start_sec'],result['end_sec']),(10,50))
                self.assertEqual(result['answer_lyrics'],'first\nmiddle\nlast')
                self.assertFalse(result['boundary_verified'])
                with self.assertRaises(ValueError):
                    apply_section_overrides([dict(row,lyric_id=8)],lyrics)
                spec=json.loads((root/'section_overrides.json').read_text(encoding='utf-8'))
                spec['1']['lead_in_first_line']=2
                (root/'section_overrides.json').write_text(json.dumps(spec),encoding='utf-8')
                with self.assertRaises(ValueError):
                    apply_section_overrides([row],lyrics)

    def test_audio_correction_keeps_lyric_passage_and_pins_recording(self):
        bounds=dict(youtube_id='AAAAAAAAAAA',lyric_id=7,audio_sha256='a'*64,
                    lead_in_start_sec=2,start_sec=9.8,end_sec=29.6)
        spec=dict(lyric_id=7,first_line=0,stop_before_line=2,reason='Complete verse',
                  lead_in_start_sec=2,lead_in_reason='Instrumental introduction',
                  context_reviewed=True,audio_boundaries=bounds)
        lyrics={7:dict(syncedLyrics='[00:10]first\n[00:20]last\n[00:30]next')}
        row=dict(id=1,youtube_id='AAAAAAAAAAA',lyric_id=7,video_duration=100)
        with patch('curate.section_specs',return_value={'1':spec}):
            result=apply_section_overrides([dict(row)],lyrics)[0]
            self.assertEqual((result['start_sec'],result['end_sec']),(9.8,29.6))
            self.assertEqual(result['answer_lyrics'],'first\nlast')
            self.assertTrue(result['audio_analyzed'])
            self.assertFalse(result['boundary_verified'])
            with self.assertRaises(ValueError):
                apply_section_overrides([dict(row,youtube_id='BBBBBBBBBBB')],lyrics)

if __name__=='__main__':unittest.main()
