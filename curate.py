REQUEST_LOCK=threading.Lock()
LAST_REQUEST=0.0
RATE_LIMIT_UNTIL=0.0

def details(video_id):
    global LAST_REQUEST,RATE_LIMIT_UNTIL
    path=CACHE/f'details-v1-{video_id}.json'
    if path.exists(): return json.loads(path.read_text(encoding='utf-8'))
    fallback=CACHE/f'catalog-proof-{video_id}.json'
    if fallback.exists(): return json.loads(fallback.read_text(encoding='utf-8'))
    with REQUEST_LOCK:
        if time.monotonic()<RATE_LIMIT_UNTIL: raise ValueError('YouTube 요청 제한(429): 확인 보류')
        time.sleep(max(0,1.3-(time.monotonic()-LAST_REQUEST)))
        LAST_REQUEST=time.monotonic()
        try:
            with urlopen(Request('https://www.youtube.com/watch?v='+video_id,headers={'User-Agent':'Mozilla/5.0','Accept-Language':'en-US,en;q=0.9'}),timeout=15) as response:
                page=response.read().decode('utf-8')
        except HTTPError as error:
            if error.code==429: RATE_LIMIT_UNTIL=time.monotonic()+60
            raise
    match=re.search(r'(?:var\s+)?ytInitialPlayerResponse\s*=\s*',page)
    if not match: raise ValueError('YouTube player metadata not available')
    data,_=json.JSONDecoder().raw_decode(page[match.end():])
    v=data.get('videoDetails',{})
    result={'id':video_id,'title':v.get('title',''),'channel':v.get('author',''),'duration':int(v.get('lengthSeconds',0)),'description':v.get('shortDescription',''),'embed_verified':data.get('playabilityStatus',{}).get('playableInEmbed') is True,'playability':data.get('playabilityStatus',{}).get('status'),'channel_id':v.get('channelId','')}
    CACHE.mkdir(exist_ok=True)
    path.write_text(json.dumps(result,ensure_ascii=False),encoding='utf-8')
    return result

def is_art_track(v):
    desc=v.get('description','').lower()
    return 'provided to youtube by' in desc and ('auto-generated by youtube' in desc or v.get('metadata_origin')=='youtube_catalog_search')

def search(query):
    import hashlib
    path=CACHE/('search-audio-v1-'+hashlib.sha256(query.encode()).hexdigest()+'.json')
    if path.exists(): return json.loads(path.read_text(encoding='utf-8'))
    env=dict(os.environ)
    env['PYTHONPATH']=str(ROOT/'.deps')+os.pathsep+env.get('PYTHONPATH','')
    result=subprocess.run([sys.executable,'-m','yt_dlp','--flat-playlist','--dump-single-json','--no-warnings','ytsearch12:'+query],capture_output=True,text=True,encoding='utf-8',env=env,timeout=75)
    if result.returncode: raise ValueError('YouTube audio search failed')
    entries=json.loads(result.stdout).get('entries',[])
    path.write_text(json.dumps(entries,ensure_ascii=False),encoding='utf-8')
    return entries

def excluded(title):
    return bool(re.search(r'\b(?:mv|m/v|music video|live|cover|remix|instrumental|inst|karaoke|piano|sped|slowed|performance|teaser|reaction|originally|japanese|jpn|chinese|mandarin)\b|뮤직비디오|노래방|직캠|라이브|안무|연주|반주|일본어|중국어',title,re.I))

def title_matches(value,song):
    artist,title=names(song)
    value=norm(value)
    return any(norm(t) and (norm(t) in value or value in norm(t) and len(value)>2) for t in [song['title'],title])

def artist_matches(value,song):
    artist,_=names(song)
    value=norm(value)
    alternates={'임창정':['Im Chang Jung'],'방탄소년단':['BANGTANTV'],'(여자)아이들':['i-dle','아이들'],'이영지':['Young Ji Lee','이영지'],'제니':['JENNIE']}
    return any(norm(a) in value for a in [artist,song['artist']]+alternates.get(song['artist'],[]) if norm(a))

def art_matches(v,song):
    if not is_art_track(v) or excluded(v['title']) or not title_matches(v['title'],song): return False
    # Album metadata before the credits is the recording identity, not a title keyword search.
    identity=v.get('catalog_performer','')
    for line in v.get('description','').splitlines()[1:]:
        if ' · ' in line:
            identity=' · '.join(line.split(' · ')[1:])
            break
    return artist_matches(identity,song) and v['embed_verified'] and v['playability'] in ['OK','OEMBED_AVAILABLE']

def catalog_details(entry,song):
    """Use YouTube's published catalog description + official oEmbed availability."""
    desc=entry.get('description') or ''
    if not desc.startswith('Provided to YouTube by '): return None
    if not artist_matches(entry.get('channel',''),song): return None
    performer=desc.split(' · ',1)[1].split('℗',1)[0] if ' · ' in desc else entry['channel'] if entry.get('channel_is_verified') is True else ''
    if not artist_matches(performer,song) or not entry.get('duration'): return None
    video_id=entry['id']
    data=request('https://www.youtube.com/oembed',{'url':'https://www.youtube.com/watch?v='+video_id,'format':'json'})
    if '<iframe' not in data.get('html','') or not title_matches(data.get('title',''),song): return None
    v=dict(id=video_id,title=data['title'],channel=data.get('author_name',entry['channel']),duration=int(entry['duration']),description=desc,embed_verified=True,playability='OEMBED_AVAILABLE',channel_id=entry.get('channel_id',''),metadata_origin='youtube_catalog_search',catalog_performer=performer)
    if not art_matches(v,song): return None
    (CACHE/f'catalog-proof-{video_id}.json').write_text(json.dumps(v,ensure_ascii=False),encoding='utf-8')
    return v

def cached_lyrics():
    result={}
    for path in CACHE.glob('*.json'):
        try:
            value=json.loads(path.read_text(encoding='utf-8'))
            if not isinstance(value,list): continue
            for item in value:
                if isinstance(item,dict) and item.get('syncedLyrics') and item.get('id'):
                    result[item['id']]=item
        except (ValueError,OSError): pass
    return result

LYRICS={}
def lyric_matches(item,song):
    return title_matches(item.get('trackName',''),song) and artist_matches(item.get('artistName',''),song) and not excluded(item.get('trackName',''))

def lyrics_for(song,more=False):
    matches=[m for m in LYRICS.values() if lyric_matches(m,song)]
    if matches and not more: return matches
    artist,title=names(song)
    for params in [dict(track_name=title,artist_name=artist),dict(track_name=re.sub(r'\([^)]*\)','',song['title']).strip(),artist_name=artist),{'q':artist+' '+title}]:
        try:
            values=request('https://lrclib.net/api/search',params)
            matches.extend(v for v in values if v.get('syncedLyrics') and lyric_matches(v,song))
        except Exception: continue
    return list({m['id']:m for m in matches}.values())

def find_pair(v,lyrics,song):
    options=[]
    for lyric in lyrics:
        if not lyric.get('duration'): continue
        delta=abs(v['duration']-float(lyric['duration']))
        if delta>2.5: continue
        try:
            start,end,answer=choose_section(parse_lrc(lyric['syncedLyrics']),v['duration'],song['section_hint'])
        except ValueError: continue
        if song['id'] in [60,79,82,97,98]:
            letters=[c for c in answer if c.isalpha()]
            if not letters or sum(c.isascii() for c in letters)/len(letters)<.8: continue
        elif song['id'] not in [1,9,18,28,35,38,45,48,61,63,64,67,68,71,77,78,80,84,85,86,89,90,91,94,95,96,99]:
            if len(re.findall(r'[가-힣]',lyric['syncedLyrics']))<20: continue
        options.append((delta,abs(end-start-30),lyric,start,end,answer))
    return min(options,key=lambda x:x[:2]) if options else None

def fill_strict(song,old):
    row=dict(song)
    row.update(youtube_id='',start_sec=None,end_sec=None,answer_lyrics='',status='missing',embed_verified=False,source_type='',audit_version=4)
    lyrics=lyrics_for(song)
    checked=set()
    audio=[]
    def inspect(entries):
        for entry in entries:
            video_id=entry.get('id') or entry.get('youtube_id')
            title=entry.get('title','')
            if not video_id or video_id in checked or excluded(title): continue
            # Do not fetch arbitrary covers that merely share a short song title.
            if title and not title_matches(title,song): continue
            checked.add(video_id)
            try: v=details(video_id)
            except Exception:
                try: v=catalog_details(entry,song)
                except Exception: v=None
                if not v: continue
            if not art_matches(v,song): continue
            if song['id']==79 and 'twin' not in v['title'].lower(): continue
            audio.append(v)
            pair=find_pair(v,lyrics,song)
            if pair: return v,pair
        return None
    artist,title=names(song)
    entries=[]
    if old.get('youtube_id'): entries.append({'id':old['youtube_id'],'title':old.get('video_title','')})
    for version in ['v3','v2']:
        path=CACHE/f"youtube-{version}-{song['id']}.json"
        if path.exists(): entries.extend(json.loads(path.read_text(encoding='utf-8')))
    queries=[f'{artist} {title} "Provided to YouTube"',f'{song["artist"]} {re.sub(r"\([^)]*\)","",song["title"])} 음원',f'{artist} {title} Topic']
    extras={77:'IVE I AM Ive IVE album audio',91:'이영지 Small girl 16 Fantasy 음원',95:'JENNIE ruby like JENNIE audio'}
    if song['id'] in extras: queries.insert(0,extras[song['id']])
    import hashlib
    for query in queries:
        cached=CACHE/('search-audio-v1-'+hashlib.sha256(query.encode()).hexdigest()+'.json')
        if cached.exists(): entries.extend(json.loads(cached.read_text(encoding='utf-8')))
    unique={}
    for entry in entries:
        key=entry.get('id')
        if key not in unique or len(entry.get('description') or '')>len(unique[key].get('description') or ''): unique[key]=entry
    entries=list(unique.values())
    def priority(entry):
        title=entry.get('title','')
        own=artist_matches(entry.get('channel',''),song)
        return (0 if own and '- topic' in entry.get('channel','').lower() else 1 if own and title_matches(title,song) and len(norm(title))<len(norm(names(song)[1]))+12 else 2 if own else 3)
    entries.sort(key=priority)
    selected=inspect(entries)
    if not selected:
        for query in queries:
            try: selected=inspect(search(query))
            except Exception: continue
            if selected: break
    if not selected and audio:
        lyrics=lyrics_for(song,more=True)
        for v in audio:
            pair=find_pair(v,lyrics,song)
            if pair: selected=v,pair;break
    if not selected:
        row['review_notes']='공식 앨범 음원과 길이가 일치하는 싱크 가사/25~35초 구간을 확보하지 못했습니다. 뮤비 대체 금지.' if audio else '임베드 가능한 공식 앨범 Art Track 미확보. 뮤비 대체 금지.'
        row['checked_candidates']=len(checked)
        return row
    v,(delta,_,lyric,start,end,answer)=selected
    row.update(youtube_id=v['id'],start_sec=start,end_sec=end,answer_lyrics=answer,status='candidate',embed_verified=True,source_type='official_art_track',video_title=v['title'],video_channel=v['channel'],video_duration=v['duration'],audio_duration=lyric['duration'],duration_delta_sec=round(delta,2),lyric_source=f'https://lrclib.net/api/get/{lyric["id"]}',lyric_id=lyric['id'],lyric_track=lyric['trackName'],lyric_artist=lyric['artistName'],evidence={'provider':v['description'].splitlines()[0],'auto_generated':True,'channel_id':v['channel_id'],'method':v.get('metadata_origin','youtube_player_metadata'),'embed_check':'oembed' if v['playability']=='OEMBED_AVAILABLE' else 'player_metadata'},section_method='same_recording_duration_matched_lrc',review_notes='공식 앨범 음원 / 25~35초 / 동일 길이 싱크 가사. 특정 멤버의 랩·첫 후렴 위치 및 줄 단위 싱크는 청취 확인 전입니다.',checked_candidates=len(checked))
    return row

def main():
    global LYRICS
    if '--cooldown' in sys.argv: time.sleep(min(60,float(sys.argv[sys.argv.index('--cooldown')+1])))
    old=json.loads((ROOT/'songs_filled.json').read_text(encoding='utf-8'))
    CACHE.mkdir(exist_ok=True)
    backup=CACHE/'before-curation-v4.json'
    if not backup.exists(): backup.write_text(json.dumps(old,ensure_ascii=False),encoding='utf-8')
    else: old=json.loads(backup.read_text(encoding='utf-8'))
    old={s['id']:s for s in old}
    LYRICS=cached_lyrics()
    with (ROOT/'songs.csv').open(encoding='utf-8-sig',newline='') as f: songs=list(csv.DictReader(f))
    for song in songs:
        for key in ['id','year','difficulty']: song[key]=int(song[key])
    results=[None]*len(songs)
    resume=ROOT/'.cache/curation-v4-progress.json'
    previous=json.loads(resume.read_text(encoding='utf-8')) if resume.exists() else []
    previous={s['id']:s for s in previous if s and s.get('youtube_id') and art_matches(details(s['youtube_id']),s)}
    workers=int(sys.argv[sys.argv.index('--workers')+1]) if '--workers' in sys.argv else 2
    with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as pool:
        jobs={pool.submit(fill_strict,s,old.get(s['id'],{})):s for s in songs if s['id'] not in previous}
        for s in songs:
            if s['id'] in previous: results[s['id']-1]=previous[s['id']]
        for job in concurrent.futures.as_completed(jobs):
            song=jobs[job]
            try: row=job.result()
            except Exception as error:
                row=dict(song,youtube_id='',start_sec=None,end_sec=None,answer_lyrics='',status='missing',audit_version=4,review_notes=str(error))
            results[row['id']-1]=row
            resume.write_text(json.dumps(results,ensure_ascii=False),encoding='utf-8')
            print(json.dumps({'id':row['id'],'audio':bool(row.get('youtube_id')),'duration':round(row['end_sec']-row['start_sec'],2) if row.get('youtube_id') else None,'checked':row.get('checked_candidates')},ensure_ascii=True),flush=True)
    write_outputs(results)

if __name__=='__main__' and '--probe' not in sys.argv: main()

